#!/usr/bin/env node
// Refresh src/models/models-dev-snapshot.ts: the offline fallback for the
// models.dev catalog, trimmed to the providers Autopilot has presets for and
// to the fields provider-catalog.ts reads.
//
//   node scripts/update-models-dev-snapshot.mjs            # fetch models.dev
//   node scripts/update-models-dev-snapshot.mjs api.json   # from a local copy
import { readFile, writeFile } from "node:fs/promises";

const PROVIDERS = (await readFile(new URL("../src/providers/presets.ts", import.meta.url), "utf8"))
  .matchAll(/modelsDevId:\s*"([^"]+)"/g);
const ids = [...new Set([...PROVIDERS].map((m) => m[1]))].sort();

const source = process.argv[2];
const all = source
  ? JSON.parse(await readFile(source, "utf8"))
  : await (await fetch("https://models.dev/api.json")).json();

const pick = (o, keys) => Object.fromEntries(keys.filter((k) => o[k] !== undefined).map((k) => [k, o[k]]));
const out = {};
for (const id of ids) {
  const p = all[id];
  if (!p) {
    console.warn(`models.dev has no provider "${id}"`);
    continue;
  }
  const models = {};
  // The snapshot is only an offline floor: the newest models per provider are
  // enough (the live catalog lists everything), and keep the bundle small.
  const newest = Object.entries(p.models ?? {})
    .sort(([, a], [, b]) => String(b.release_date ?? "").localeCompare(String(a.release_date ?? "")))
    .slice(0, 80);
  for (const [mid, m] of newest) {
    if (m.tool_call !== true || m.status === "deprecated") continue;
    if (!(m.modalities?.input ?? ["text"]).includes("text")) continue;
    models[mid] = {
      ...pick(m, ["id", "name", "release_date", "attachment", "reasoning", "reasoning_options", "tool_call", "temperature", "interleaved", "limit", "canonical_model_id"]),
      modalities: { input: m.modalities?.input ?? ["text"] },
      ...(m.cost ? { cost: pick(m.cost, ["input", "output", "cache_read", "cache_write"]) } : {}),
    };
  }
  out[id] = { id: p.id, name: p.name, models };
}

const banner = `// Generated by scripts/update-models-dev-snapshot.mjs from https://models.dev/api.json
// on ${new Date().toISOString().slice(0, 10)}. Offline fallback only: the live catalog replaces it at startup.
// Do not edit by hand.
import type { ModelsDevProvider } from "./provider-catalog.js";

export const MODELS_DEV_SNAPSHOT: Record<string, ModelsDevProvider> = `;
await writeFile(new URL("../src/models/models-dev-snapshot.ts", import.meta.url), banner + JSON.stringify(out) + ";\n");
console.log(`wrote ${ids.length} providers: ${ids.join(", ")}`);
