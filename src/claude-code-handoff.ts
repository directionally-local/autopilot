/**
 * `autopilot --from-claude-code`: pick up the most recent Claude Code conversation in this
 * folder, e.g. after Claude Code stopped on a usage or rate limit (#1127).
 *
 * Claude Code keeps one JSONL transcript per conversation under
 * `~/.claude/projects/<encoded folder>/<session id>.jsonl` (`$CLAUDE_CONFIG_DIR/projects` when
 * that is set). The folder name is the working directory with every character other than a
 * letter or digit replaced by `-` (`/Users/ana/my_app` → `-Users-ana-my-app`); very long
 * names are cut and given a suffix, so a prefix match is the fallback. The encoding is lossy
 * (`/a/b-c` and `/a/b/c` share a folder), so a transcript is only used when the `cwd` its
 * entries record is this folder.
 *
 * Each line is one entry: `{type: "user" | "assistant" | "summary" | "system" | …, message:
 * {role, content}, cwd, sessionId, timestamp, isMeta?, isSidechain?, isApiErrorMessage?, …}`.
 * User content is a string or blocks (`text`, `tool_result` with `tool_use_id`, `content`,
 * `is_error`); assistant content is blocks (`text`, `thinking`, `tool_use` with `id`, `name`,
 * `input`). Anything this module doesn't recognise is skipped, never fatal.
 *
 * Everything here is local: the transcript is read from disk and the handoff it builds becomes
 * the first message of a new session, which goes only to the model the person already uses.
 * Likely secrets are redacted first.
 */
import { open, readdir, stat } from "node:fs/promises";
import { homedir } from "node:os";
import { isAbsolute, join, relative } from "node:path";
import { redactLikelySecrets } from "./secrets.js";

/** The handoff message's ceiling (about 3–4k tokens), whatever the transcript holds. */
export const HANDOFF_MAX_CHARS = 12_000;
/** How much of a transcript's end is read: recent context lives there, and transcripts can be large. */
const TAIL_BYTES = 8 * 1024 * 1024;
/** How much of its start is read for the title (the first request), when the tail doesn't reach it. */
const HEAD_BYTES = 256 * 1024;
/** Claude Code cuts a project folder's name at this length (and adds a suffix). */
const MAX_ENCODED_NAME = 200;

export interface ClaudeCodeConversation {
  /** The transcript file. */
  path: string;
  /** Claude Code's session id (the file name without .jsonl). */
  sessionId: string;
  /** When it was last written to (the file's modification time). */
  updatedAt: Date;
  /** A short name: the first request's first line. */
  title: string;
  /** The first request, when it isn't also the last. */
  firstRequest?: string;
  /** The most recent thing the person asked. */
  lastRequest: string;
  /** Claude's last reply text (API error notices, such as the limit message itself, excluded). */
  lastAssistantMessage?: string;
  /** Files Claude created or edited, oldest first, relative to the folder when inside it. */
  filesChanged: string[];
  /** Files Claude read and didn't change. */
  filesRead: string[];
  /** Shell commands Claude ran, oldest first. */
  commands: string[];
  /** The last failed tool calls: what was run, and the start of its error. */
  errors: Array<{ tool: string; error: string }>;
}

/** Where Claude Code keeps its data: `$CLAUDE_CONFIG_DIR`, else `~/.claude`. */
export function claudeCodeConfigDir(env: NodeJS.ProcessEnv = process.env, home: string = homedir()): string {
  const configured = env.CLAUDE_CONFIG_DIR?.trim();
  return configured ? configured : join(home, ".claude");
}

/** The name of a folder's directory under `projects/`: every non-alphanumeric character becomes `-`. */
export function encodeClaudeCodeProjectPath(cwd: string): string {
  return cwd.replace(/[^a-zA-Z0-9]/g, "-");
}

interface Entry {
  type?: unknown;
  message?: { role?: unknown; content?: unknown; model?: unknown };
  cwd?: unknown;
  timestamp?: unknown;
  isMeta?: unknown;
  isSidechain?: unknown;
  isApiErrorMessage?: unknown;
  isCompactSummary?: unknown;
  isVisibleInTranscriptOnly?: unknown;
  summary?: unknown;
}

interface Block {
  type?: unknown;
  text?: unknown;
  id?: unknown;
  name?: unknown;
  input?: unknown;
  tool_use_id?: unknown;
  content?: unknown;
  is_error?: unknown;
}

/** Lines Claude Code writes as user messages that the person didn't type. */
const NOT_A_REQUEST = [
  /^<command-(name|message|args)>/,
  /^<local-command-(stdout|stderr|caveat)>/,
  /^<bash-(input|stdout|stderr)>/,
  /^<user-memory-input>/,
  /^<system-reminder>/,
  /^Caveat: The messages below were generated by the user/,
  /^\[Request interrupted by user/,
  /^This session is being continued from a previous conversation/,
];

function textOf(content: unknown): string {
  if (typeof content === "string") return content;
  if (!Array.isArray(content)) return "";
  return content
    .map((block: Block) => (block && block.type === "text" && typeof block.text === "string" ? block.text : ""))
    .filter(Boolean)
    .join("\n");
}

function blocks(content: unknown): Block[] {
  return Array.isArray(content) ? (content.filter((b) => b && typeof b === "object") as Block[]) : [];
}

function oneLine(text: string, max: number): string {
  const line = text.replace(/\s+/g, " ").trim();
  return line.length > max ? `${line.slice(0, max - 1).trimEnd()}…` : line;
}

function clip(text: string, max: number): string {
  const trimmed = text.trim();
  return trimmed.length > max ? `${trimmed.slice(0, max - 1).trimEnd()}…` : trimmed;
}

/** The end of a long text, which is where a reply's conclusion or an error's cause usually is. */
function clipStart(text: string, max: number): string {
  const trimmed = text.trim();
  return trimmed.length > max ? `…${trimmed.slice(trimmed.length - max + 1).trimStart()}` : trimmed;
}

function displayPath(file: string, cwd: string): string {
  if (!isAbsolute(file)) return file;
  const rel = relative(cwd, file);
  return rel && !rel.startsWith("..") && !isAbsolute(rel) ? rel : file;
}

function pushUnique(list: string[], value: string): void {
  const at = list.indexOf(value);
  if (at !== -1) list.splice(at, 1);
  list.push(value);
}

/**
 * What a transcript says: the requests, what Claude did, and its last reply. `undefined` when
 * it holds no request the person typed (an empty or command-only conversation), or when it
 * belongs to another folder.
 */
export function parseClaudeCodeTranscript(
  text: string,
  cwd: string,
): Omit<ClaudeCodeConversation, "path" | "sessionId" | "updatedAt"> | undefined {
  const requests: string[] = [];
  let summary: string | undefined;
  let lastAssistantMessage: string | undefined;
  let otherFolder = false;
  let thisFolder = false;
  const filesChanged: string[] = [];
  const filesRead: string[] = [];
  const commands: string[] = [];
  const errors: Array<{ tool: string; error: string }> = [];
  const toolUses = new Map<string, string>();

  for (const line of text.split("\n")) {
    if (!line.trim()) continue;
    let entry: Entry;
    try {
      entry = JSON.parse(line) as Entry;
    } catch {
      continue; // a cut first line (we read the tail) or a partial last write
    }
    if (!entry || typeof entry !== "object") continue;
    if (entry.type === "summary" && typeof entry.summary === "string") {
      summary ??= entry.summary;
      continue;
    }
    if (typeof entry.cwd === "string") {
      if (entry.cwd === cwd) thisFolder = true;
      else otherFolder = true;
    }
    // Subagents' own turns are their business; the main conversation reports what they found.
    if (entry.isSidechain === true) continue;
    const message = entry.message;
    if (!message || typeof message !== "object") continue;

    if (entry.type === "user" && message.role === "user") {
      for (const block of blocks(message.content)) {
        if (block.type !== "tool_result" || block.is_error !== true) continue;
        const tool = typeof block.tool_use_id === "string" ? toolUses.get(block.tool_use_id) : undefined;
        const error = textOf(block.content) || (typeof block.content === "string" ? block.content : "");
        if (error.trim()) errors.push({ tool: tool ?? "a tool call", error: clipStart(error, 400) });
      }
      if (entry.isMeta === true || entry.isCompactSummary === true || entry.isVisibleInTranscriptOnly === true) continue;
      const typed = textOf(message.content).trim();
      if (!typed || NOT_A_REQUEST.some((pattern) => pattern.test(typed))) continue;
      requests.push(typed);
      continue;
    }

    if (entry.type === "assistant" && message.role === "assistant") {
      // The limit notice ("Claude AI usage limit reached", "API Error: …") is Claude Code's, not Claude's.
      if (entry.isApiErrorMessage === true || message.model === "<synthetic>") continue;
      const reply = textOf(message.content).trim();
      if (reply) lastAssistantMessage = reply;
      for (const block of blocks(message.content)) {
        if (block.type !== "tool_use" || typeof block.name !== "string") continue;
        const input = (block.input && typeof block.input === "object" ? block.input : {}) as Record<string, unknown>;
        const file = typeof input.file_path === "string" ? input.file_path : typeof input.notebook_path === "string" ? input.notebook_path : undefined;
        let label = block.name;
        if (["Edit", "MultiEdit", "Write", "NotebookEdit"].includes(block.name) && file) {
          pushUnique(filesChanged, displayPath(file, cwd));
          label = `${block.name} ${displayPath(file, cwd)}`;
        } else if (block.name === "Read" && file) {
          pushUnique(filesRead, displayPath(file, cwd));
          label = `Read ${displayPath(file, cwd)}`;
        } else if (block.name === "Bash" && typeof input.command === "string") {
          commands.push(input.command);
          label = `\`${oneLine(input.command, 120)}\``;
        }
        if (typeof block.id === "string") toolUses.set(block.id, label);
      }
    }
  }

  if (otherFolder && !thisFolder) return undefined;
  const lastRequest = requests.at(-1);
  if (!lastRequest) return undefined;
  const firstRequest = requests[0]!;
  return {
    title: redactLikelySecrets(oneLine(firstRequest.split("\n")[0] ?? firstRequest, 60) || oneLine(summary ?? "", 60)),
    ...(requests.length > 1 && firstRequest !== lastRequest ? { firstRequest } : {}),
    lastRequest,
    ...(lastAssistantMessage ? { lastAssistantMessage } : {}),
    filesChanged,
    filesRead: filesRead.filter((file) => !filesChanged.includes(file)),
    commands,
    errors: errors.slice(-3),
  };
}

/** The project folders a working directory's transcripts may be in. */
async function projectDirs(projectsDir: string, cwd: string): Promise<string[]> {
  const encoded = encodeClaudeCodeProjectPath(cwd);
  // Older Claude Code releases replaced only path separators (and dots).
  const legacy = cwd.replace(/[\\/:.]/g, "-");
  const names = new Set([encoded, legacy]);
  if (encoded.length > MAX_ENCODED_NAME) {
    const prefix = encoded.slice(0, MAX_ENCODED_NAME);
    const all = await readdir(projectsDir).catch(() => [] as string[]);
    for (const name of all) if (name.startsWith(prefix)) names.add(name);
  }
  return [...names].map((name) => join(projectsDir, name));
}

async function readTranscript(path: string, size: number): Promise<string> {
  const handle = await open(path, "r");
  try {
    if (size <= TAIL_BYTES + HEAD_BYTES) {
      const buffer = Buffer.alloc(size);
      await handle.read(buffer, 0, size, 0);
      return buffer.toString("utf8");
    }
    // A long conversation: its start (for the first request) and its recent end.
    const head = Buffer.alloc(HEAD_BYTES);
    await handle.read(head, 0, HEAD_BYTES, 0);
    const tail = Buffer.alloc(TAIL_BYTES);
    await handle.read(tail, 0, TAIL_BYTES, size - TAIL_BYTES);
    // Cut lines at either seam fail to parse and are skipped.
    return `${head.toString("utf8")}\n${tail.toString("utf8")}`;
  } finally {
    await handle.close();
  }
}

/**
 * The most recently updated Claude Code conversation started in `cwd`, or undefined when there
 * is none. Reads only the transcripts under that folder's project directory.
 */
export async function findLatestClaudeCodeConversation(options: {
  cwd: string;
  configDir?: string;
}): Promise<ClaudeCodeConversation | undefined> {
  const projectsDir = join(options.configDir ?? claudeCodeConfigDir(), "projects");
  const candidates: Array<{ path: string; sessionId: string; mtime: Date; size: number }> = [];
  for (const dir of await projectDirs(projectsDir, options.cwd)) {
    const names = await readdir(dir).catch(() => [] as string[]);
    for (const name of names) {
      // agent-*.jsonl are subagents' transcripts, not conversations.
      if (!name.endsWith(".jsonl") || name.startsWith("agent-")) continue;
      const path = join(dir, name);
      const info = await stat(path).catch(() => undefined);
      if (!info?.isFile()) continue;
      candidates.push({ path, sessionId: name.slice(0, -".jsonl".length), mtime: info.mtime, size: info.size });
    }
  }
  candidates.sort((a, b) => b.mtime.getTime() - a.mtime.getTime());
  for (const candidate of candidates) {
    const text = await readTranscript(candidate.path, candidate.size).catch(() => undefined);
    if (text === undefined) continue;
    const parsed = parseClaudeCodeTranscript(text, options.cwd);
    if (parsed) return { path: candidate.path, sessionId: candidate.sessionId, updatedAt: candidate.mtime, ...parsed };
  }
  return undefined;
}

/** "4 minutes ago", for the question. */
export function formatAgo(then: Date, now: Date = new Date()): string {
  const seconds = Math.max(0, Math.round((now.getTime() - then.getTime()) / 1000));
  const unit = (n: number, word: string) => `${n} ${word}${n === 1 ? "" : "s"} ago`;
  if (seconds < 60) return "less than a minute ago";
  const minutes = Math.round(seconds / 60);
  if (minutes < 60) return unit(minutes, "minute");
  const hours = Math.round(minutes / 60);
  if (hours < 48) return unit(hours, "hour");
  return unit(Math.round(hours / 24), "day");
}

/**
 * The question `--from-claude-code` asks before starting. The title has a line of its own,
 * so a long one never pushes "[Enter / n]" across the terminal's edge.
 */
export function handoffQuestion(conversation: Pick<ClaudeCodeConversation, "updatedAt" | "title">, now: Date = new Date()): string {
  return `Found your Claude Code conversation from ${formatAgo(conversation.updatedAt, now)}:\n  ‘${conversation.title}’\nContinue it here? [Enter / n] `;
}

/** Said after a yes when first-run setup comes before the session: the handoff waits for it. */
export function handoffAfterSetupLine(conversation: Pick<ClaudeCodeConversation, "title">): string {
  return `First, choose how it should think; then I'll continue ‘${conversation.title}’.`;
}

/** Why there's nothing to continue. */
export function noConversationMessage(cwd: string): string {
  return `No Claude Code conversation found for this folder (${cwd}). Run this in the folder where you used Claude Code.`;
}

/** What the new session shows for its first message (the handoff itself goes to the model). */
export function handoffDisplay(conversation: Pick<ClaudeCodeConversation, "title">): string {
  return `Continue my Claude Code conversation ‘${conversation.title}’ (its last request, what was done, and its last message are attached)`;
}

function listSection(title: string, items: string[], max: number, itemMax: number): string | undefined {
  if (items.length === 0) return undefined;
  const shown = items.slice(-max).map((item) => `- ${oneLine(item, itemMax)}`);
  const more = items.length > max ? `- (${items.length - max} earlier not shown)\n` : "";
  return `${title}:\n${more}${shown.join("\n")}`;
}

/**
 * The first message of the new session: the task, what was done, and where Claude stopped,
 * capped at HANDOFF_MAX_CHARS and with likely secrets redacted.
 */
export function buildHandoffMessage(conversation: ClaudeCodeConversation, maxChars: number = HANDOFF_MAX_CHARS): string {
  const done = [
    listSection("Files changed", conversation.filesChanged, 30, 200),
    listSection("Files read", conversation.filesRead, 15, 200),
    listSection("Commands run", conversation.commands, 15, 200),
    conversation.errors.length
      ? `Last errors (they may have been fixed since):\n${conversation.errors.map((e) => `- ${e.tool}: ${e.error.replace(/\n+/g, "\n  ")}`).join("\n")}`
      : undefined,
  ].filter(Boolean);
  const sections = [
    "I was working on this in Claude Code and it stopped (it hit its usage or rate limit). Please pick the task up from here.",
    "Below is a summary from my local Claude Code transcript. The files on disk are the source of truth: check them before changing anything, since the last steps may be half done.",
    conversation.firstRequest ? `## How the task started\n${clip(conversation.firstRequest, 1_500)}` : undefined,
    `## My last request\n${clip(conversation.lastRequest, 3_000)}`,
    `## What was done\n${done.length ? done.join("\n\n") : "No files changed and no commands run yet."}`,
    conversation.lastAssistantMessage ? `## Claude Code's last message\n${clipStart(conversation.lastAssistantMessage, 3_000)}` : undefined,
  ].filter(Boolean);
  const message = redactLikelySecrets(sections.join("\n\n"));
  return message.length > maxChars ? `${message.slice(0, maxChars - 30).trimEnd()}\n\n[handoff cut to fit]` : message;
}

/** The answer to the question: Enter (or y) continues, n (or Esc) doesn't, Ctrl-C cancels. */
export type HandoffAnswer = "yes" | "no" | "cancel";

/**
 * Ask the question and read one key: Enter or y continues, n or Esc declines, Ctrl-C cancels.
 * Other keys are ignored. Without a raw-mode terminal it reads a line instead.
 */
export function askEnterOrNo(
  question: string,
  io: {
    input: NodeJS.ReadableStream & { isTTY?: boolean; setRawMode?: (mode: boolean) => unknown };
    output: { write(text: string): unknown };
  },
): Promise<HandoffAnswer> {
  io.output.write(question);
  const raw = io.input.isTTY === true && typeof io.input.setRawMode === "function";
  return new Promise((resolve) => {
    let line = "";
    const finish = (answer: HandoffAnswer) => {
      io.input.off("data", onData);
      io.input.off("end", onEnd);
      if (raw) io.input.setRawMode!(false);
      io.input.pause();
      io.output.write(answer === "yes" ? "\n" : answer === "no" ? "n\n" : "\n");
      resolve(answer);
    };
    const onEnd = () => finish("cancel");
    const onData = (chunk: Buffer | string) => {
      const text = typeof chunk === "string" ? chunk : chunk.toString("utf8");
      if (raw) {
        for (const key of text) {
          if (key === "\r" || key === "\n" || key === "y" || key === "Y") return finish("yes");
          if (key === "n" || key === "N" || key === "\x1b") return finish("no");
          if (key === "\x03" || key === "\x04") return finish("cancel");
        }
        return;
      }
      line += text;
      const end = line.indexOf("\n");
      if (end === -1) return;
      const answer = line.slice(0, end).trim().toLowerCase();
      finish(answer === "" || answer === "y" || answer === "yes" ? "yes" : "no");
    };
    if (raw) io.input.setRawMode!(true);
    io.input.on("data", onData);
    io.input.on("end", onEnd);
    io.input.resume();
  });
}
