import { describe, it, before, after } from "node:test";
import assert from "node:assert";
import { mkdtemp, mkdir, rm, utimes, writeFile } from "node:fs/promises";
import { PassThrough } from "node:stream";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
  HANDOFF_MAX_CHARS,
  askEnterOrNo,
  buildHandoffMessage,
  claudeCodeConfigDir,
  encodeClaudeCodeProjectPath,
  findLatestClaudeCodeConversation,
  formatAgo,
  handoffQuestion,
  parseClaudeCodeTranscript,
  type ClaudeCodeConversation,
} from "./claude-code-handoff.js";

const CWD = "/home/ana/shop_app";
const SESSION = "8f1c2a7e-3b4d-4e5f-9a0b-1c2d3e4f5a6b";
const KEY = `sk-or-v1-${"a1b2c3d4".repeat(8)}`;

/** A Claude Code transcript, shaped like the JSONL Claude Code writes, ending on a usage limit. */
function transcript(cwd = CWD, sessionId = SESSION): string {
  let n = 0;
  const base = () => ({ parentUuid: n ? `u${n - 1}` : null, isSidechain: false, userType: "external", cwd, sessionId, version: "2.1.250", gitBranch: "main", uuid: `u${n++}`, timestamp: `2026-11-03T01:${String(n).padStart(2, "0")}:00.000Z` });
  const user = (content: unknown, extra: Record<string, unknown> = {}) => ({ ...base(), type: "user", message: { role: "user", content }, ...extra });
  const assistant = (content: unknown[], extra: Record<string, unknown> = {}) => ({ ...base(), type: "assistant", requestId: "req_1", message: { id: "msg_1", type: "message", role: "assistant", model: "claude-opus-4-1", content, stop_reason: "tool_use", usage: { input_tokens: 10, output_tokens: 5 } }, ...extra });
  const lines = [
    { type: "summary", summary: "Checkout discount rounding fix", leafUuid: "u9" },
    user("<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>"),
    user("Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages.", { isMeta: true }),
    user("fix the discount bug\nCodes over 50% come out negative."),
    assistant([
      { type: "thinking", thinking: "Look at checkout first.", signature: "x" },
      { type: "text", text: "I'll look at the checkout code." },
      { type: "tool_use", id: "toolu_01", name: "Read", input: { file_path: `${cwd}/src/checkout.ts` } },
    ]),
    user([{ tool_use_id: "toolu_01", type: "tool_result", content: "export function applyDiscount() {}" }], { toolUseResult: { type: "text" } }),
    assistant([{ type: "tool_use", id: "toolu_02", name: "Edit", input: { file_path: `${cwd}/src/checkout.ts`, old_string: "a", new_string: "b" } }]),
    user([{ tool_use_id: "toolu_02", type: "tool_result", content: "The file has been updated." }]),
    assistant([{ type: "tool_use", id: "toolu_03", name: "Bash", input: { command: `OPENROUTER_KEY=${KEY} npm test -- checkout`, description: "Run tests" } }]),
    user([{ tool_use_id: "toolu_03", type: "tool_result", is_error: true, content: "Exit code 1\nFAIL src/checkout.test.ts\n  expected 40 to equal 45" }]),
    assistant([{ type: "tool_use", id: "toolu_04", name: "Write", input: { file_path: `${cwd}/src/checkout.test.ts`, content: "…" } }]),
    user([{ tool_use_id: "toolu_04", type: "tool_result", content: "File created" }]),
    // A subagent's own turn: not the main conversation.
    assistant([{ type: "tool_use", id: "toolu_s1", name: "Edit", input: { file_path: `${cwd}/src/elsewhere.ts` } }], { isSidechain: true }),
    user("also round to cents"),
    assistant([{ type: "text", text: "Rounding now happens after the discount; the remaining failure is the 45 vs 40 expectation in checkout.test.ts." }]),
    user("[Request interrupted by user]"),
    // Claude Code's own limit notice is not Claude's last message.
    { ...base(), type: "assistant", isApiErrorMessage: true, message: { id: "x", model: "<synthetic>", role: "assistant", type: "message", content: [{ type: "text", text: "Claude AI usage limit reached|1762160400" }] } },
  ];
  return `${lines.map((line) => JSON.stringify(line)).join("\n")}\n`;
}

describe("Claude Code handoff: where transcripts are", () => {
  it("encodes a folder the way Claude Code names its project directory", () => {
    assert.strictEqual(encodeClaudeCodeProjectPath("/Users/ana/code/shop"), "-Users-ana-code-shop");
    assert.strictEqual(encodeClaudeCodeProjectPath("/home/ana/shop_app/v1.2"), "-home-ana-shop-app-v1-2");
    assert.strictEqual(encodeClaudeCodeProjectPath("C:\\Users\\ana\\shop"), "C--Users-ana-shop");
  });

  it("uses CLAUDE_CONFIG_DIR when set, else ~/.claude", () => {
    assert.strictEqual(claudeCodeConfigDir({ CLAUDE_CONFIG_DIR: "/cfg/claude" }, "/home/ana"), "/cfg/claude");
    assert.strictEqual(claudeCodeConfigDir({}, "/home/ana"), join("/home/ana", ".claude"));
  });
});

describe("Claude Code handoff: reading a transcript", () => {
  it("finds the requests, what was done and the last reply, skipping commands, subagents and the limit notice", () => {
    const parsed = parseClaudeCodeTranscript(transcript(), CWD)!;
    assert.ok(parsed);
    assert.strictEqual(parsed.title, "fix the discount bug");
    assert.strictEqual(parsed.firstRequest, "fix the discount bug\nCodes over 50% come out negative.");
    assert.strictEqual(parsed.lastRequest, "also round to cents");
    assert.match(parsed.lastAssistantMessage!, /^Rounding now happens after the discount/);
    assert.deepStrictEqual(parsed.filesChanged, ["src/checkout.ts", "src/checkout.test.ts"]);
    assert.deepStrictEqual(parsed.filesRead, []);
    assert.deepStrictEqual(parsed.commands, [`OPENROUTER_KEY=${KEY} npm test -- checkout`]);
    assert.strictEqual(parsed.errors.length, 1);
    assert.match(parsed.errors[0]!.tool, /npm test -- checkout/);
    assert.match(parsed.errors[0]!.error, /expected 40 to equal 45/);
  });

  it("ignores another folder's conversation, unparseable lines, and a conversation with no request", () => {
    assert.strictEqual(parseClaudeCodeTranscript(transcript("/home/ana/shop/app"), CWD), undefined);
    assert.ok(parseClaudeCodeTranscript(`{"cut line\n${transcript()}not json\n`, CWD));
    const onlyCommands = JSON.stringify({ type: "user", cwd: CWD, message: { role: "user", content: "<command-name>/model</command-name>" } });
    assert.strictEqual(parseClaudeCodeTranscript(onlyCommands, CWD), undefined);
    assert.strictEqual(parseClaudeCodeTranscript("", CWD), undefined);
  });
});

describe("Claude Code handoff: the message", () => {
  it("carries the last request, what was done and the last reply, with secrets redacted", () => {
    const parsed = parseClaudeCodeTranscript(transcript(), CWD)!;
    const message = buildHandoffMessage({ ...parsed, path: "/x.jsonl", sessionId: SESSION, updatedAt: new Date() });
    assert.match(message, /## My last request\nalso round to cents/);
    assert.match(message, /## How the task started\nfix the discount bug/);
    assert.match(message, /Files changed:\n- src\/checkout.ts\n- src\/checkout.test.ts/);
    assert.match(message, /Commands run:\n- OPENROUTER_KEY=\[REDACTED_PROVIDER_SECRET\] npm test -- checkout/);
    assert.match(message, /Last errors \(they may have been fixed since\):/);
    assert.match(message, /## Claude Code's last message\nRounding now happens/);
    assert.ok(!message.includes(KEY), "the key never reaches the handoff");
    assert.ok(!message.includes("usage limit reached|"));
  });

  it("stays under the size cap however long the transcript", () => {
    const long = "x".repeat(50_000);
    const conversation: ClaudeCodeConversation = {
      path: "/x.jsonl", sessionId: SESSION, updatedAt: new Date(), title: "t", lastRequest: long, lastAssistantMessage: long,
      filesChanged: Array.from({ length: 500 }, (_, i) => `src/file-${i}.ts`), filesRead: [],
      commands: Array.from({ length: 500 }, () => long), errors: [{ tool: "Bash", error: long }],
    };
    const message = buildHandoffMessage(conversation);
    assert.ok(message.length <= HANDOFF_MAX_CHARS, `${message.length}`);
    assert.match(message, /\(470 earlier not shown\)/);
    assert.ok(buildHandoffMessage(conversation, 2_000).length <= 2_000);
  });
});

describe("Claude Code handoff: the question", () => {
  it("says when and what, and reads Enter, n and Ctrl-C", async () => {
    const now = new Date("2026-11-03T10:00:00Z");
    assert.strictEqual(
      handoffQuestion({ updatedAt: new Date("2026-11-03T09:56:00Z"), title: "fix the discount bug" }, now),
      "Found your Claude Code conversation from 4 minutes ago: ‘fix the discount bug’. Continue it here? [Enter / n] ",
    );
    assert.strictEqual(formatAgo(new Date("2026-11-03T09:59:30Z"), now), "less than a minute ago");
    assert.strictEqual(formatAgo(new Date("2026-11-03T09:59:00Z"), now), "1 minute ago");
    assert.strictEqual(formatAgo(new Date("2026-11-03T07:00:00Z"), now), "3 hours ago");
    assert.strictEqual(formatAgo(new Date("2026-10-30T10:00:00Z"), now), "4 days ago");

    const ask = async (keys: string, raw: boolean) => {
      const input = Object.assign(new PassThrough(), raw ? { isTTY: true, setRawMode: (_mode: boolean) => input } : {});
      let written = "";
      const answer = askEnterOrNo("Continue? ", { input, output: { write: (text: string) => (written += text) } });
      input.write(keys);
      return { answer: await answer, written };
    };
    assert.strictEqual((await ask("\r", true)).answer, "yes");
    assert.strictEqual((await ask("xn", true)).answer, "no");
    assert.strictEqual((await ask("\x03", true)).answer, "cancel");
    assert.strictEqual((await ask("\n", false)).answer, "yes");
    assert.strictEqual((await ask("no\n", false)).answer, "no");
    assert.match((await ask("\r", true)).written, /^Continue\? /);
  });
});

describe("Claude Code handoff: finding the latest conversation", () => {
  let config: string;
  before(async () => {
    config = await mkdtemp(join(tmpdir(), "cc-handoff-"));
  });
  after(async () => {
    await rm(config, { recursive: true, force: true });
  });

  it("picks this folder's most recently updated transcript, skipping subagents, other folders and empty ones", async () => {
    const dir = join(config, "projects", encodeClaudeCodeProjectPath(CWD));
    await mkdir(dir, { recursive: true });
    const older = join(dir, "11111111-0000-0000-0000-000000000000.jsonl");
    const latest = join(dir, `${SESSION}.jsonl`);
    const emptyNewest = join(dir, "22222222-0000-0000-0000-000000000000.jsonl");
    const agent = join(dir, "agent-3f2a.jsonl");
    // /home/ana/shop/app encodes to the same directory name; it must not be picked.
    const otherFolder = join(dir, "33333333-0000-0000-0000-000000000000.jsonl");
    await writeFile(older, transcript().replace(/also round to cents/g, "an older conversation"));
    await writeFile(latest, transcript());
    await writeFile(emptyNewest, "");
    await writeFile(agent, transcript());
    await writeFile(otherFolder, transcript("/home/ana/shop/app"));
    const at = (path: string, minutesAgo: number) => utimes(path, new Date(), new Date(Date.now() - minutesAgo * 60_000));
    await at(older, 60);
    await at(latest, 4);
    await at(emptyNewest, 1);
    await at(agent, 0);
    await at(otherFolder, 0);

    const found = await findLatestClaudeCodeConversation({ cwd: CWD, configDir: config });
    assert.ok(found);
    assert.strictEqual(found.sessionId, SESSION);
    assert.strictEqual(found.path, latest);
    assert.strictEqual(found.lastRequest, "also round to cents");
  });

  it("returns nothing for a folder Claude Code was never used in", async () => {
    assert.strictEqual(await findLatestClaudeCodeConversation({ cwd: "/somewhere/else", configDir: config }), undefined);
    assert.strictEqual(await findLatestClaudeCodeConversation({ cwd: CWD, configDir: join(config, "missing") }), undefined);
  });
});
